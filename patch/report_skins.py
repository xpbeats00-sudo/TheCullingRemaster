"""Per-skin audit table for the custom weapon skins (docs/ANIMATED_SKIN_AUDIT.md).

For every catalog skin from make_camos.py: the skin package and its camo
texture go through audit_assets.audit() (re-save, tag walk, texture platform
data; audit_assets.py main() resolves the soft references), and its tags say
what it really is:
a static 4-colour camo, or one carrying the GeoSkin/BC tags of the animated
(scrolling) path. Nothing here runs the game: "runtime" columns are left to
in-game checks.

usage: python report_skins.py <Paks dir> <out.md>
"""
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import audit_assets  # noqa: E402
import make_camos  # noqa: E402
from ue_package import UPackage  # noqa: E402

CATALOG = os.path.join(HERE, "..", "server", "data", "catalog.json")
SRC = os.path.join(HERE, "src")


RUNTIME = """## Runtime status (from in-game reports, 2026-11-03)

The game is a cooked UE 4.15.3 shipping build. I cannot run it or see its
screen, so every runtime fact below comes from the user's in-game reports.

- **Static camos (2179 skins):** shown in game on the weapons. They do not
  animate. The weapon material (PM_Weapon_Master) has no time input on its
  camo layer, so a texture swap alone can never move.
- **Animated path (all 37 weapons, earlier build):** each skin carried GeoSkin
  (a mesh copy using a copy of Chainsaw_A_MI, the only compiled material
  permutation with a time-driven panner) plus BC (a full-colour camo image).
  Selecting one gave "Serialization Error: Corrupt data found". Fixing stale
  mip offsets in 37 GP textures (cooked_texture.relocate) did not cure it. The
  37 weapons were reverted to static camos.
- **Diagnostic build (current):** only the Ice Axe keeps test skins, one per
  piece of the animated path:

  | Ice Axe skin | What it isolates | Result |
  |---|---|---|
  | Frost Plasma | control: plain static camo | awaiting report |
  | Lava Storm | BC override only | awaiting report |
  | Teal Current | GeoSkin = stock FireAxe_C mesh | awaiting report |
  | Blue Tempest | GeoSkin = mesh copy with the stock material | awaiting report |
  | Arcane Surge | full animated path (mesh copy + chainsaw material copy) | awaiting report |

  The first skin in this list that shows the error names the broken piece.
  Until then, no custom skin is claimed as animated.
- **FPS:** not measured for the animated skins. None is active outside the
  Ice Axe tests, and the game exposes no frame-time readout to the tools here.
"""


def rel_path(game_path):
    return os.path.join(SRC, "Victory", "Content", *game_path[len("/Game/"):].split("/")) + ".uasset"


def skin_tags(path):
    up = UPackage(open(path, "rb").read())
    data = up.exports[0]["data"]
    tags = {}
    for name, ptype, start, voff, size in make_camos.iter_tags(up, data):
        if ptype == "AssetObjectProperty":
            tags[name] = data[voff + 4:voff + size - 1].decode("latin1")
    return tags


def check(path, cache):
    if path not in cache:
        if not os.path.exists(path):
            cache[path] = "missing"
        else:
            try:
                audit_assets.audit(path, None)
                cache[path] = "ok"
            except Exception as ex:   # Problem or a parse error: both are failures
                cache[path] = "%s: %s" % (type(ex).__name__, ex)
    return cache[path]


def main(paks_dir, out):
    skins = [i for i in json.load(open(CATALOG)) if i.get("source") == "xp-camos"]
    cache, rows = {}, []
    for s in skins:
        path = rel_path(s["asset"])
        weapon = os.path.basename(path).split("_XP_")[0]
        status = check(path, cache)
        tags = skin_tags(path) if status == "ok" else {}
        camo = tags.get("Camo")
        camo_status = check(rel_path(camo.split(".")[0]), cache) if camo and camo.startswith("/Game/") else "no camo tag"
        kind = "animated path (GeoSkin+BC)" if "GeoSkin" in tags and "BC" in tags else \
            "GeoSkin only" if "GeoSkin" in tags else "BC only" if "BC" in tags else "static camo"
        rows.append((weapon, s["displayName"], s["tid"], int(s["purchaseCost"]), kind, status, camo_status))

    fails = [r for r in rows if r[5] != "ok" or r[6] != "ok"]
    kinds = collections.Counter(r[4] for r in rows)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Animated Skin Audit\n\n")
        f.write("Generated by `patch/report_skins.py`. Static checks only: the game was not run for this table.\n\n")
        f.write("## Summary\n\n")
        f.write("| Measure | Count |\n|---|---|\n")
        f.write("| Custom weapon skins in the catalog | %d |\n" % len(rows))
        f.write("| Weapons | %d |\n" % len({r[0] for r in rows}))
        f.write("| Camos | %d |\n" % len({r[1] for r in rows}))
        for k, n in sorted(kinds.items()):
            f.write("| Skins of kind: %s | %d |\n" % (k, n))
        f.write("| Skin or camo texture failing the structural audit | %d |\n" % len(fails))
        f.write("| Verified animating in game | 0 (not verified; see below) |\n\n")
        f.write(RUNTIME + "\n")
        if fails:
            f.write("## Failures\n\n| Weapon | Camo | Skin package | Camo texture |\n|---|---|---|---|\n")
            for r in fails:
                f.write("| %s | %s | %s | %s |\n" % (r[0], r[1], r[5], r[6]))
            f.write("\n")
        f.write("## Every skin\n\n")
        f.write("Structural = package re-saves byte-identically and its tags walk cleanly; camo textures also have valid platform data. "
                "Runtime animation is unverified for every row.\n\n")
        f.write("| Weapon | Camo | Item ID | Price | Kind | Skin package | Camo texture | Animated in game |\n")
        f.write("|---|---|---|---|---|---|---|---|\n")
        for r in sorted(rows):
            f.write("| %s | %s | %d | %d | %s | %s | %s | unverified |\n" % r)
    print("%d skins, %d failing, kinds %s" % (len(rows), len(fails), dict(kinds)))


if __name__ == "__main__":
    main(*sys.argv[1:])
