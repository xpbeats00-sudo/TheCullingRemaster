"""Card ID -> menu image for every calling card (stock and custom).

The menu shows the local player's card from GetLocalPlayerCullingCardImagePath,
which comes back blank when the engine hasn't loaded the card's texture yet
(the card then shows no art). CardImages.js falls back to this map, keyed by
the card's ItemID, so the menu never depends on that texture load. Values are
paths under /images/culling-cards/ without ".png" (stock flags live in Flags/).

usage: python make_card_image_map.py <Paks dir>
"""
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import make_camos  # noqa: E402
from build_catalog import pak_entries  # noqa: E402
from patch_assets import find_in_paks  # noqa: E402
from ue_package import UPackage  # noqa: E402

UI = os.path.join(HERE, "src", "Victory", "Content", "uiresources")
OUT = os.path.join(UI, "FrontEnd", "js", "CardImageMap.js")
CARDS = "Victory/Content/Cosmetics/CullingCards/"


def card_fields(data):
    up = UPackage(data)
    d = up.exports[0]["data"]
    out = {}
    for name, ptype, start, voff, size in make_camos.iter_tags(up, d):
        if name in ("ItemID", "CullingCard"):
            out[name] = d[voff + 4:voff + size - 1].decode("latin1")
    return out


def main(paks_dir):
    stock_cards, pngs = set(), {}
    for pk in stock_paks(paks_dir):
        for e in pak_entries(pk):
            n = e[1].replace("../../../", "")
            if n.startswith(CARDS) and n.endswith(".uasset") and "/Source/" not in n:
                stock_cards.add(n)
            if "/images/culling-cards/" in n and n.endswith(".png"):
                rel = n.split("/images/culling-cards/", 1)[1][:-4]
                pngs[os.path.basename(rel)] = rel
    for f in glob.glob(os.path.join(UI, "images", "culling-cards", "*.png")):
        name = os.path.basename(f)[:-4]
        pngs[name] = name

    datas = list(find_in_paks(paks_dir, stock_cards).values())
    datas += [open(f, "rb").read() for f in glob.glob(os.path.join(HERE, "src", CARDS, "CullingCardXP_*.uasset"))]
    mapping, missing = {}, []
    for data in datas:
        f = card_fields(data)
        if "ItemID" not in f or "CullingCard" not in f:
            continue
        texture = f["CullingCard"].rsplit(".", 1)[-1]
        if texture in pngs:
            mapping[f["ItemID"]] = pngs[texture]
        else:
            missing.append((f["ItemID"], texture))
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("// Generated by make_card_image_map.py: card ItemID -> /images/culling-cards/<value>.png\n")
        fh.write("var CullingCardImages = %s;\n" % json.dumps(mapping, sort_keys=True))
    print("%d cards mapped, %d without a menu image %s" % (len(mapping), len(missing), missing[:5]))


if __name__ == "__main__":
    main(sys.argv[1])
