/* Weather over a match: clouds, moon/sun, sky light, fog and rain change on
 * seeded timers. Part of the native module: showdown_rounds.c includes this
 * file and calls weather_tick(gm) once a second from sd_should_end (the
 * GameMode's "should the match end" check, which AShooterGameMode::Tick
 * calls once a second while the match is InProgress).
 *
 * Off unless the match URL asks for it: the game mode's OptionsString
 * (AGameModeBase +0x400) carries
 *     ?Weather=<clear|cloudy|rainy|storm|foggy>   start state and theme
 *     ?WeatherSeed=<n>                             the schedule's seed
 *     ?WeatherCycle=0                              keep the start state
 * Without Weather= nothing here runs. Without WeatherSeed= the seed comes
 * from the CPU clock (the match is then not reproducible).
 *
 * The weather is a pure function of (seed, preset, seconds InProgress):
 * every machine given the same seed computes the same states, blends,
 * rain and lightning (weather_state below; make_weather.py has the same
 * schedule in Python and test_weather_native.py checks they agree). A
 * future netplay host only has to send the seed.
 *
 * What it drives, found by full object path in the map's Lighting level
 * (weather_maps.h, generated by make_weather.py; StaticFindObject resolves
 * the path, so no class or field offsets are needed):
 *   - ExponentialHeightFogComponent: SetFogDensity (from a visibility in
 *     metres, with the map's fog height constants) and SetStartDistance;
 *   - DirectionalLightComponent (sun or moon) and SkyLightComponent:
 *     SetIntensity (map base x the state's factor; a lightning flash
 *     multiplies both for one tick);
 *   - the sky dome's MaterialInstanceDynamic (PM_Sky): SetScalarParameterValue
 *     for "Cloud opacity", "Cloud speed" and, on night maps, "Stars brightness";
 *     on night maps thicker cloud is also darker (SetVectorParameterValue
 *     "Cloud color" toward a dark overcast, less of the moon's rim light on
 *     it: "Rim light brightness", "Whole Cloud Rim light"). Thick cloud in the
 *     night level's own bright cloud colour, rim lit by the moon, read as a
 *     grey day sky on Jungle Night. Day maps keep their bright clouds;
 *   - every object is found again each tick and used only if live (a weak
 *     pointer to it resolves); the rain's particle system is looked up (or
 *     loaded again) right before each spawn, since the garbage collector
 *     frees one that isn't playing;
 *   - rain: /Game/Remaster/Weather/P_Rain_{Light,Heavy,Storm} (make_rain.py),
 *     spawned with UGameplayStatics::SpawnEmitterAttached on the local
 *     player's pawn root (kept in a weak pointer; a new pawn gets a new
 *     emitter), deactivated (it then finishes its drops and destroys
 *     itself) when the rain level changes;
 *   - shelter: while it rains, upward line traces (Visibility, complex) from
 *     just above the pawn's centre - straight up and at 4 points 250 units
 *     around - say whether a roof is overhead. Covered (the centre and at
 *     least 2 of the 4 hit within WX_ROOF_UP) for WX_SHELTER_TICKS ticks in a
 *     row turns the rain off (deactivated: the drops already falling finish);
 *     open for as many ticks turns it back on. The camera-attached drops
 *     would otherwise fall through roofs (their GPU collision only sees the
 *     depth buffer). A small overhang (the centre only) keeps the rain.
 */

