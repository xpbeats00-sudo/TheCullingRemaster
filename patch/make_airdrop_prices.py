"""Airdrop prices: every airdrop costs 25% less FUNC.

Where an airdrop's price lives
------------------------------
The FUNC an airdrop costs in a match is ActivityResourceCost, an IntProperty
of each AirDropPackageDataAsset (Victory/Content/AirDropPackages/*.uasset).
It is the only place the price is defined:
- the game reads it from the selected package; the HUD gets it from the game
  as SetAirdropProgress(progress, MaxRating, Rating, ...) and shows
  "{matchData.currRating}/{matchData.maxRating}" (hud/hud.html, hud/js/hud.js);
- the menu's Airdrop screen gets it from the game too (GetAirdropData, each
  airdrop's .Cost) and shows it beside the name (FrontEnd.html);
- no localisation text, HUD or menu script holds a number for it;
- the server never prices airdrops: they are catalog items that are owned or
  unlocked by level, not bought (purchasable false, every cost 0 in
  server/data/catalog.json), and match results report FUNC earned, not spent.
Surprise Me! (AirDrop_zRandom) stores no price: it hands out a random kit
from the others, so it costs what that kit costs.

The rule
--------
new = round(stock x 0.75), to the nearest integer, halves rounding up (the
property is an integer). In integer arithmetic: (3 * stock + 2) // 4, i.e.
floor(stock * 3/4 + 1/2). The stock prices are multiples of 5, so a
quarter-off price ends in .0, .25, .5 or .75: .25 rounds down, .5 and .75 up.

Always from the stock assets (stock_paks.py: never the patch pak, so running
this twice still takes 25% off once). Writes the patched packages to patch/src
(same size: the 4-byte value changes in place), the table to
patch/loot/airdrop_prices.json and docs/AIRDROP_PRICES.md.

usage: python make_airdrop_prices.py [Paks dir]
"""
import json
import os
import re
import struct
import sys
from collections import OrderedDict
from fractions import Fraction

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from stock_paks import paks_dir, read_stock  # noqa: E402
from uasset import Package  # noqa: E402

SRC = os.path.join(HERE, "src")
OUT_JSON = os.path.join(HERE, "loot", "airdrop_prices.json")
OUT_DOC = os.path.join(HERE, "..", "docs", "AIRDROP_PRICES.md")
AIRDROPS = re.compile(r"^Victory/Content/AirDropPackages/[A-Za-z0-9_]+\.uasset$")
PRICE_FACTOR = Fraction(3, 4)          # 25% off
PRICE_PROPERTY = "ActivityResourceCost"


def new_price(stock):
    """round(stock * 3/4), halves up, as an integer."""
    stock = int(stock)
    n, d = PRICE_FACTOR.numerator, PRICE_FACTOR.denominator
    return (2 * stock * n + d) // (2 * d)


def price_slot(pkg, export):
    """(offset, value) of the export's stored ActivityResourceCost, or None."""
    for name, ptype, idx, voff, size, extra, value in pkg.props(export):
        if name == PRICE_PROPERTY:
            assert ptype == "IntProperty" and size == 4 and idx == 0, (export, ptype, size, idx)
            return voff, value
    return None


def reprice(rel, data):
    """The patched package and its table row."""
    pkg = Package(data)
    e = pkg.exports[0]
    assert pkg.ref(e["class"]) == "AirDropPackageDataAsset", (rel, pkg.ref(e["class"]))
    props = {p[0]: p[6] for p in pkg.props(e["name"])}
    row = OrderedDict([("asset", rel), ("export", e["name"]), ("name", props.get("DisplayName", e["name"])),
                       ("itemId", int(props["ItemID"])), ("enabled", props.get("bEnabled", True)),
                       ("random", bool(props.get("bIsRandom", False)))])
    slot = price_slot(pkg, e["name"])
    if slot is None:
        row.update(stock=None, new=None, offset=None)
        return None, row
    off, stock = slot
    new = new_price(stock)
    out = bytearray(data)
    struct.pack_into("<i", out, off, new)
    row.update(stock=stock, new=new, offset=off)
    return bytes(out), row


def doc(rows):
    priced = [r for r in rows if r["stock"] is not None]
    out = ["# Airdrop prices", "",
           "Generated by `patch/make_airdrop_prices.py` from the game's cooked assets (also in",
           "`patch/loot/airdrop_prices.json`). Every airdrop costs 25% less FUNC: **new = round(stock x 0.75)**,",
           "to the nearest whole FUNC, halves rounding up (integer form: `(3 * stock + 2) // 4`).", "",
           "## Where the price lives", "",
           "| Place | What it holds | Changed |", "|---|---|---|",
           "| `Victory/Content/AirDropPackages/*.uasset`, `ActivityResourceCost` (IntProperty) | the price, the only definition | yes: each one, in `patch/src` |",
           "| HUD airdrop meter `{currRating}/{maxRating}` (`hud/hud.html`, `hud/js/hud.js` `SetAirdropProgress`) | shows MaxRating, which the game sends | nothing to change (no number in the UI) |",
           "| Menu Airdrop screen `{PreviewAirdrop.Cost}` (`FrontEnd/FrontEnd.html`, `GetAirdropData`) | shows Cost, which the game sends | nothing to change |",
           "| Localisation (`FrontEnd.json`, `hud.json`) | no airdrop price | - |",
           "| Server (`server/data/catalog.json`) | airdrops are owned or unlocked, never bought: no price | - (checked by `server/test/airdrop_prices.test.js`) |",
           "| `patch/loot/loot_tables.json`, `docs/LOOT_TABLE_REFERENCE.md` | `funcCost` (now the new price) and `stockFuncCost` | yes |", "",
           "Surprise Me! (`AirDrop_zRandom`) stores no price: it gives a random kit from the others and costs what that kit costs.", "",
           "The game's tip \"The Bait Crate Airdrop can be called for free\" (FrontEnd.json) disagrees with the stock data, which "
           "stores 70 for it; that is the stock game's, unchanged here (it has no number to update).", "",
           "**Build**: `patch/src` isn't in git, so run `python patch/make_airdrop_prices.py <Paks dir>` on the build machine "
           "before `make_release.py`; the release pak then carries the 43 patched packages. "
           "`python patch/test_airdrop_prices.py <Paks dir>` checks them.", "",
           "## Every airdrop", "",
           "| Airdrop | Asset | ItemID | Stock FUNC | x 0.75 | New FUNC | Note |", "|---|---|---:|---:|---:|---:|---|"]
    for r in sorted(rows, key=lambda r: r["name"].lower()):
        note = []
        if r["enabled"] is False:
            note.append("disabled in the game (bEnabled false)")
        if r["stock"] is None:
            note.append("no stored price" + (": random kit" if r["random"] else ""))
            out.append("| %s | `%s` | %d | - | - | - | %s |" % (r["name"], os.path.basename(r["asset"]), r["itemId"], "; ".join(note)))
            continue
        exact = Fraction(r["stock"]) * PRICE_FACTOR
        out.append("| %s | `%s` | %d | %d | %s | %d | %s |" % (
            r["name"], os.path.basename(r["asset"]), r["itemId"], r["stock"], _dec(exact), r["new"], "; ".join(note)))
    total_s, total_n = sum(r["stock"] for r in priced), sum(r["new"] for r in priced)
    out += ["", "%d priced airdrops; total %d FUNC -> %d FUNC (%.2f%% of stock; rounding moves each one by at most 0.5 FUNC)." % (
        len(priced), total_s, total_n, 100.0 * total_n / total_s), ""]
    return "\n".join(out)


def _dec(f):
    return ("%.2f" % float(f)).rstrip("0").rstrip(".")


def main(paks):
    stock = read_stock(paks, AIRDROPS)
    if not stock:
        sys.exit("no AirDropPackages in %s" % paks)
    rows = []
    for rel in sorted(stock):
        patched, row = reprice(rel, stock[rel])
        rows.append(row)
        if patched is None:
            print("  %-22s no stored price (kept)" % row["export"])
            continue
        out = os.path.join(SRC, rel)
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "wb") as f:
            f.write(patched)
        print("  %-22s %3d -> %3d FUNC" % (row["export"], row["stock"], row["new"]))
    table = OrderedDict([("source", "patch/make_airdrop_prices.py, from the game's stock AirDropPackages"),
                         ("property", PRICE_PROPERTY), ("factor", "3/4"),
                         ("rounding", "nearest integer, halves up: (3 * stock + 2) // 4"),
                         ("airdrops", [OrderedDict((k, v) for k, v in r.items() if k != "offset") for r in rows])])
    with open(OUT_JSON, "w", newline="\n") as f:
        json.dump(table, f, indent=1)
        f.write("\n")
    with open(OUT_DOC, "w", newline="\n", encoding="utf-8") as f:
        f.write(doc(rows))
    print("%d airdrops -> %s, %s" % (len(rows), os.path.relpath(OUT_JSON, HERE), os.path.relpath(OUT_DOC, HERE)))
    return rows


if __name__ == "__main__":
    main(paks_dir(sys.argv[1] if len(sys.argv) > 1 else None))
